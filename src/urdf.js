// URDF / SRDF export of the parametric robot (URDF units: m, rad, kg).
import { BOX, CYL } from './collide.js';
import { LEG_NAMES } from './robot.js';

const M = 0.001;
const f = v => { const s = (Math.abs(v) < 1e-12 ? 0 : v).toFixed(6); return s.replace(/\.?0+$/, '') || '0'; };
const xyz = a => a.map(v => f(v * M)).join(' ');
const vec = a => a.map(f).join(' ');
const hex = c => [(c >> 16 & 255) / 255, (c >> 8 & 255) / 255, (c & 255) / 255].map(v => v.toFixed(3)).join(' ');

function shapeVolume(s) { return s.type === BOX ? 8 * s.hx * s.hy * s.hz : Math.PI * s.r * s.r * 2 * s.h; }
/** Inertia tensor of a shape (unit mass) about its own centre, in the link frame (mm^2). */
function shapeInertia(s) {
  let d;
  if (s.type === BOX) d = [(s.hy * s.hy + s.hz * s.hz) * 4 / 12, (s.hx * s.hx + s.hz * s.hz) * 4 / 12, (s.hx * s.hx + s.hy * s.hy) * 4 / 12];
  else { const a = (3 * s.r * s.r + 4 * s.h * s.h) / 12; d = [a, a, s.r * s.r / 2]; }
  const R = s.lR, I = new Array(9).fill(0);
  for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) for (let k = 0; k < 3; k++) I[3 * i + j] += R[3 * i + k] * d[k] * R[3 * j + k];
  return I;
}
function linkInertia(L) {
  // mass distributed over the link's shapes by volume; parallel-axis shift to the link COM
  const vol = L.shapes.reduce((a, s) => a + shapeVolume(s), 0);
  const I = new Array(9).fill(0);
  if (!vol) { const e = L.mass * 1e-4; return [e, 0, 0, e, 0, e]; }
  for (const s of L.shapes) {
    const m = L.mass * shapeVolume(s) / vol, Is = shapeInertia(s);
    const r = [s.lp[0] - L.com[0], s.lp[1] - L.com[1], s.lp[2] - L.com[2]], r2 = r[0] * r[0] + r[1] * r[1] + r[2] * r[2];
    for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) I[3 * i + j] += m * (Is[3 * i + j] + (i === j ? r2 : 0) - r[i] * r[j]);
  }
  const k = M * M; // mm^2 -> m^2
  return [I[0] * k, I[1] * k, I[2] * k, I[4] * k, I[5] * k, I[8] * k];
}

export function toURDF(robot, name = 'ship_block_support_robot') {
  const out = [];
  out.push('<?xml version="1.0"?>');
  out.push(`<!-- Generated by the ship-block robot design tool. Units: m / rad / kg. Parameters (mm): ${JSON.stringify(robot.P)} -->`);
  out.push(`<robot name="${name}">`);
  const mats = new Map();
  for (const s of robot.shapes) if (!mats.has(s.color)) mats.set(s.color, `mat_${s.color.toString(16).padStart(6, '0')}`);
  for (const [c, n] of mats) out.push(`  <material name="${n}"><color rgba="${hex(c)} ${c === 0xd9434f ? 0.55 : 1}"/></material>`);
  for (const L of robot.links) {
    out.push(`  <link name="${L.name}">`);
    const I = linkInertia(L);
    out.push(`    <inertial><origin xyz="${xyz(L.com)}" rpy="0 0 0"/><mass value="${f(L.mass)}"/><inertia ixx="${I[0].toExponential(4)}" ixy="${I[1].toExponential(4)}" ixz="${I[2].toExponential(4)}" iyy="${I[3].toExponential(4)}" iyz="${I[4].toExponential(4)}" izz="${I[5].toExponential(4)}"/></inertial>`);
    for (const tag of ['visual', 'collision']) for (const s of L.shapes) {
      const geo = s.type === BOX ? `<box size="${xyz([2 * s.hx, 2 * s.hy, 2 * s.hz])}"/>` : `<cylinder radius="${f(s.r * M)}" length="${f(2 * s.h * M)}"/>`;
      const mat = tag === 'visual' ? `<material name="${mats.get(s.color)}"/>` : '';
      out.push(`    <${tag} name="${s.name}${tag === 'collision' ? '_col' : ''}"><origin xyz="${xyz(s.lp)}" rpy="${vec(s.lRPY)}"/><geometry>${geo}</geometry>${mat}</${tag}>`);
    }
    out.push('  </link>');
  }
  for (const L of robot.links) {
    if (L.parent < 0) continue;
    out.push(`  <joint name="${L.jname}" type="${L.jtype}">`);
    out.push(`    <parent link="${robot.links[L.parent].name}"/><child link="${L.name}"/>`);
    out.push(`    <origin xyz="${xyz(L.oP)}" rpy="${vec(L.oRPY)}"/>`);
    if (L.jtype !== 'fixed') {
      out.push(`    <axis xyz="${vec(L.axis)}"/>`);
      if (L.jtype === 'revolute') out.push(`    <limit lower="${f(L.lower)}" upper="${f(L.upper)}" effort="100" velocity="2.0"/>`);
      else if (L.jtype === 'prismatic') out.push(`    <limit lower="${f(L.lower * M)}" upper="${f(L.upper * M)}" effort="2000" velocity="0.05"/>`);
      else out.push('    <limit effort="20" velocity="10.0"/>');
      if (L.mimic) out.push(`    <mimic joint="${L.mimic}" multiplier="1" offset="0"/>`);
    }
    out.push('  </joint>');
  }
  out.push('</robot>');
  return out.join('\n') + '\n';
}

/** Minimal SRDF for MoveIt2: one group per leg, a lift group, floating virtual joint, adjacent-link collision exemptions. */
export function toSRDF(robot, name = 'ship_block_support_robot') {
  const out = ['<?xml version="1.0"?>', `<robot name="${name}">`];
  out.push('  <virtual_joint name="world_to_base" type="floating" parent_frame="world" child_link="base_link"/>');
  for (const n of LEG_NAMES) {
    out.push(`  <group name="leg_${n}"><chain base_link="base_link" tip_link="${n}_foot"/></group>`);
    out.push(`  <end_effector name="wheel_${n}" parent_link="${n}_foot" group="leg_${n}"/>`);
  }
  out.push('  <group name="lift">' + robot.links.filter(L => L.group === 'lift' && L.jtype !== 'fixed').map(L => `<joint name="${L.jname}"/>`).join('') + '</group>');
  out.push('  <group name="legs">' + LEG_NAMES.map(n => `<group name="leg_${n}"/>`).join('') + '</group>');
  const seen = new Set();
  for (const k of robot.linkAdj) {
    const a = Math.floor(k / 1000), b = k % 1000;
    if (seen.has(k)) continue; seen.add(k);
    out.push(`  <disable_collisions link1="${robot.links[a].name}" link2="${robot.links[b].name}" reason="Adjacent"/>`);
  }
  out.push('</robot>');
  return out.join('\n') + '\n';
}

/** Joint names in state order (q index -> URDF joint name); slide joints share one value. */
export function jointNames(robot) {
  const names = new Array(23).fill(null);
  for (const L of robot.links) if (L.qi >= 0 && !L.mimic) names[L.qi] = L.jname;
  return names;
}
